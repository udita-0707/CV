"""Render the Markdown write-ups from ``*.tmpl.md`` templates and ``src.report_values``.

``{{key}}`` inserts a formatted value and ``{{table:name}}`` a Markdown table. Rendering
fails if any placeholder is unknown, so no number in the output is typed by hand.
Run from the repository root: ``.venv/bin/python -m src.render_reports``.
"""
from __future__ import annotations

import re
from pathlib import Path

from .config import project_root
from .report_values import Table, collect, fmt, table_markdown

TEMPLATES = {
    "milestones/m4/README.tmpl.md": "milestones/m4/README.md",
    "milestones/m5/failure_analysis.tmpl.md": "milestones/m5/failure_analysis.md",
    "presentation/m4_m5/slides_outline.tmpl.md": "presentation/m4_m5/slides_outline.md",
    "presentation/m4_m5/viva_prep.tmpl.md": "presentation/m4_m5/viva_prep.md",  # local only (gitignored)
}
PLACEHOLDER = re.compile(r"\{\{\s*(table:)?([A-Za-z0-9_]+)\s*\}\}")


def render(text: str, values: dict[str, tuple[object, str]], tables: dict[str, Table]) -> str:
    missing: list[str] = []

    def replace(match: re.Match) -> str:
        is_table, key = match.group(1), match.group(2)
        if is_table:
            if key in tables:
                return table_markdown(tables[key])
        elif key in values:
            return fmt(*values[key], target="md")
        missing.append(match.group(0))
        return match.group(0)

    rendered = PLACEHOLDER.sub(replace, text)
    if missing:
        raise KeyError(f"unresolved placeholders: {sorted(set(missing))}")
    return rendered


def render_all(root: Path | None = None) -> list[Path]:
    root = (root or project_root()).resolve()
    values, tables = collect(root)
    written = []
    for template, output in TEMPLATES.items():
        source = root / template
        if not source.exists():
            continue
        banner = f"<!-- Generated by `python -m src.render_reports` from `{Path(template).name}`. Edit the template, not this file. -->\n\n"
        target = root / output
        target.write_text(banner + render(source.read_text(), values, tables))
        written.append(target)
    return written


def main() -> None:
    for path in render_all():
        print(f"rendered {path}")


if __name__ == "__main__":
    main()
