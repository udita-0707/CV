"""Generate the paper's numbers, tables and figure copies from ``results/``.

Writes ``paper/generated/values.tex`` (``\\val{key}`` macros), one
``paper/generated/tab_<name>.tex`` per table, and copies the figures into
``paper/figures/`` so the folder compiles on its own (e.g. on Overleaf).
Run from the repository root: ``.venv/bin/python paper/make_tables.py``.
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.report_values import collect, fmt, table_latex  # noqa: E402

FIGURES = {
    "per_id_sensitivity_by_fold.png": "results/m4/figures/per_id_sensitivity_by_fold.png",
    "paired_differences.png": "results/m4/figures/paired_differences.png",
    "fnr_vs_positive_cells.png": "results/m4/figures/fnr_vs_positive_cells.png",
    "error_concentration.png": "results/m5/figures/error_concentration.png",
    "reliability_diagram.png": "results/m5/figures/reliability_diagram.png",
    "grid_top_false_negatives.png": "results/m5/figures/grid_top_false_negatives.png",
    "grid_top_false_positives.png": "results/m5/figures/grid_top_false_positives.png",
    "grid_worst_patient_ids.png": "results/m5/figures/grid_worst_patient_ids.png",
}
BANNER = "% Generated by paper/make_tables.py from results/. Do not edit by hand.\n"


def main() -> None:
    values, tables = collect(ROOT)
    out = ROOT / "paper" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    lines = [BANNER]
    for key, (raw, kind) in sorted(values.items()):
        lines.append(f"\\expandafter\\def\\csname val@{key}\\endcsname{{{fmt(raw, kind, 'tex')}}}\n")
    (out / "values.tex").write_text("".join(lines))
    for name, table in tables.items():
        (out / f"tab_{name}.tex").write_text(BANNER + table_latex(table))
    figures = ROOT / "paper" / "figures"
    figures.mkdir(exist_ok=True)
    for name, source in FIGURES.items():
        shutil.copyfile(ROOT / source, figures / name)
    print(f"wrote {len(values)} values, {len(tables)} tables, {len(FIGURES)} figures")


if __name__ == "__main__":
    main()
